"""Generate the release-build entrypoints from the candidate build workflows.

A per-release workflow in release-tracking builds every project of a release in one run. Its generator
already knows that every build is a ``release-build`` candidate, and it computes each build matrix ahead
of time by running this repository's own matrix scripts at the pinned commit. The helper jobs around each
candidate build (``policy``, ``compute-matrix``, ``candidate-image-preflight``, ``prepare-build-matrix``)
therefore add nothing to such a run except clutter.

``<family>-release.yaml`` is the candidate workflow's ``build`` job alone. It takes the precomputed matrix
as ``candidate-matrix`` and evaluates the same build policy as its first step, so the run-time checks stay;
it refuses anything but a release-build candidate without image preflight. The files are generated, never
edited by hand: run this script after changing a candidate workflow, and pre-commit checks they match.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WORKFLOWS = ROOT / ".github/workflows"
FAMILIES = ("conda-cpp-build", "conda-python-build", "wheels-build")
MATRIX_INPUT = "candidate-matrix"
POLICY_STEP = "release-policy"
HEADER = (
    "# Generated by ci/release_build_entrypoints.py from {source}; do not edit.\n"
    "# The release-build entrypoint: the candidate build job alone, with a precomputed matrix.\n"
)
MATRIX_INPUT_TEXT = f"""      {MATRIX_INPUT}:
        description: >-
          Precomputed build matrix (the JSON compute-matrix and prepare-build-matrix would produce), written
          into the per-release workflow by its generator.
        required: true
        type: string
"""
POLICY_STEPS = f"""      - name: Evaluate the build policy for this release build
        id: {POLICY_STEP}
        uses: $/.github/actions/evaluate-build-policy
        with:
          inputs-json: ${{{{ toJSON(inputs) }}}}
          build-type: release-candidate
      - name: Require a release-build candidate without image preflight
        env:
          RUN_CANDIDATE: ${{{{ steps.{POLICY_STEP}.outputs.run-candidate }}}}
          IMAGE_PREFLIGHT: ${{{{ steps.{POLICY_STEP}.outputs.image-preflight }}}}
          CANDIDATE_ROLE: ${{{{ inputs.candidate-role }}}}
        run: |
          if [[ "${{RUN_CANDIDATE}}" != true || "${{IMAGE_PREFLIGHT}}" != false || "${{CANDIDATE_ROLE}}" != release-build ]]; then
            echo "release build entrypoints run only release-build candidates without image preflight" >&2
            exit 1
          fi
"""
REPLACEMENTS = (
    ("needs.policy.outputs.", f"steps.{POLICY_STEP}.outputs."),
    # Only read by steps that run when image preflight input is given, which the policy step refuses.
    ("${{ needs.prepare-build-matrix.outputs.preflight-document-sha256 }}", '""'),
)


class EntrypointError(ValueError):
    """A candidate workflow no longer has the shape this generator transforms."""


def _block(lines: list[str], start: int) -> int:
    """Return the end of the two-space-indented job block starting at ``start``."""
    end = start + 1
    while end < len(lines) and not re.match(r"^  \S", lines[end]) and not re.match(r"^\S", lines[end]):
        end += 1
    return end


def generate(text: str, family: str) -> str:
    """Return the release-build entrypoint for one candidate workflow's text."""
    lines = text.splitlines(keepends=True)
    try:
        jobs = lines.index("jobs:\n")
        inputs = lines.index("    inputs:\n")
        build = lines.index("  build:\n", jobs)
    except ValueError as error:
        raise EntrypointError(f"{family}-candidate.yaml has no jobs, inputs or build job") from error
    end = _block(lines, build)
    job = lines[build:end]
    edited: list[str] = []
    seen = {"needs": 0, "if": 0, "matrix": 0, "steps": 0}
    for line in job:
        if line.startswith("    needs: "):
            seen["needs"] += 1
            continue
        if line.startswith("    if: "):
            seen["if"] += 1
            continue
        if re.match(r"^      matrix: \$\{\{ fromJSON\(needs\.[a-z-]+\.outputs\.matrix\) \}\}\n$", line):
            seen["matrix"] += 1
            edited.append(f"      matrix: ${{{{ fromJSON(inputs.{MATRIX_INPUT}) }}}}\n")
            continue
        edited.append(line)
        if line == "    steps:\n":
            seen["steps"] += 1
            edited.append(POLICY_STEPS)
    if seen["needs"] != 1 or seen["matrix"] != 1 or seen["steps"] != 1 or seen["if"] > 1:
        raise EntrypointError(f"{family}-candidate.yaml build job changed shape: {seen}")
    body = "".join(edited)
    for old, new in REPLACEMENTS:
        body = body.replace(old, new)
    if "needs." in body:
        raise EntrypointError(f"{family}-candidate.yaml build job reads another job: {re.findall(r'needs[.][\\w.-]+', body)}")
    preamble = lines[:jobs]
    preamble.insert(inputs + 1, MATRIX_INPUT_TEXT)
    # Keep the copyright line first; the generated-file notice follows it.
    copyright_lines = 1 if preamble and preamble[0].startswith("# Copyright") else 0
    preamble.insert(copyright_lines, HEADER.format(source=f".github/workflows/{family}-candidate.yaml"))
    result = "".join(preamble) + "jobs:\n" + body
    document = yaml.safe_load(result)
    if list(document["jobs"]) != ["build"] or MATRIX_INPUT not in document[True]["workflow_call"]["inputs"]:
        raise EntrypointError(f"generated {family}-release.yaml is not a single build job with {MATRIX_INPUT}")
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if a generated entrypoint is out of date.")
    args = parser.parse_args(argv)
    stale = []
    for family in FAMILIES:
        expected = generate((WORKFLOWS / f"{family}-candidate.yaml").read_text(), family)
        target = WORKFLOWS / f"{family}-release.yaml"
        if target.exists() and target.read_text() == expected:
            continue
        if args.check:
            stale.append(target.name)
        else:
            target.write_text(expected)
    if stale:
        print(f"regenerate with ci/release_build_entrypoints.py: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
