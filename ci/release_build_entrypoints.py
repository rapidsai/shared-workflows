"""Generate the release-build entrypoints from the candidate build workflows.

A per-release workflow in release-tracking builds every project of a release in one run. Its generator
already knows that every build is a ``release-build`` candidate, and it computes each build matrix ahead
of time by running this repository's own matrix scripts at the pinned commit. The helper jobs around each
candidate build (``policy``, ``compute-matrix``, ``candidate-image-preflight``, ``prepare-build-matrix``)
therefore add nothing to such a run except clutter.

``<family>-release.yaml`` is the candidate workflow's ``build`` job alone. It takes the precomputed matrix
as ``candidate-matrix`` and evaluates the same build policy as its first step, so the run-time checks stay;
it refuses anything but a release-build candidate without image preflight.

Every row runs in its train's own CI image from private GHCR, pinned by digest: ``candidate-image-map`` maps each
row's ``candidate_image_key`` to ``ghcr.io/rapidsai/release-candidates/<ci-conda|ci-wheel>@sha256:...`` (the
release file's early ci-imgs check supplies it), the container pulls with the run's own token, and the first step
fails unless the image is such a reference. A missing key makes the image empty, which GitHub would run on the
host; that check refuses it before anything else runs.

The files are generated, never edited by hand: run this script after changing a candidate workflow, and
pre-commit checks they match.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WORKFLOWS = ROOT / ".github/workflows"
FAMILIES = ("conda-cpp-build", "conda-python-build", "wheels-build")
MATRIX_INPUT = "candidate-matrix"
IMAGE_MAP_INPUT = "candidate-image-map"
IMAGE_FAMILIES = {"conda-cpp-build": "ci-conda", "conda-python-build": "ci-conda", "wheels-build": "ci-wheel"}
IMAGE_EXPRESSION = f"${{{{ fromJSON(inputs.{IMAGE_MAP_INPUT})[matrix.candidate_image_key] }}}}"
POLICY_STEP = "release-policy"
HEADER = (
    "# Generated by ci/release_build_entrypoints.py from {source}; do not edit.\n"
    "# The release-build entrypoint: the candidate build job alone, with a precomputed matrix.\n"
)
MATRIX_INPUT_TEXT = f"""      {MATRIX_INPUT}:
        description: >-
          Precomputed build matrix (the JSON compute-matrix and prepare-build-matrix would produce), written
          into the per-release workflow by its generator.
        required: true
        type: string
"""
IMAGE_MAP_INPUT_TEXT = f"""      {IMAGE_MAP_INPUT}:
        description: >-
          JSON map from each matrix row's candidate_image_key to its train's verified CI image,
          ghcr.io/rapidsai/release-candidates/<ci-conda|ci-wheel>@sha256:<digest>.
        required: true
        type: string
"""
CONTAINER_LINES = f"""      image: {IMAGE_EXPRESSION} # zizmor: ignore[unpinned-images] - the first step requires a digest
      credentials:
        username: ${{{{ github.actor }}}}
        password: ${{{{ github.token }}}}
"""
IMAGE_STEP = r"""      - name: Require the train's verified candidate image
        env:
          IMAGE: {expression}
          FAMILY: {family}
        run: |
          if [[ ! "${{IMAGE}}" =~ ^ghcr\.io/rapidsai/release-candidates/${{FAMILY}}@sha256:[0-9a-f]{{64}}$ ]]; then
            echo "this row has no verified candidate image (got '${{IMAGE}}'); release builds run only in their train's ${{FAMILY}} image" >&2
            exit 1
          fi
          # Dependency setup puts the exact image into the row's reuse key.
          echo "RELEASE_CANDIDATE_RUNTIME_IMAGE=${{IMAGE}}" >> "${{GITHUB_ENV}}"
"""
SETUP_STEP = "      - name: Prepare candidate dependencies and build policy\n"
REUSE_STEP_ID = "row-reuse"
REUSED_CONDITION = f"steps.{REUSE_STEP_ID}.outputs.reused != 'true'"
REUSE_STEP = f"""      - name: Reuse this row from an earlier complete run
        id: {REUSE_STEP_ID}
        if: ${{{{ env.RELEASE_CANDIDATE_ROW_REUSE_KEY != '' }}}}
        run: candidate-row-reuse
"""
POLICY_STEPS = f"""      - name: Evaluate the build policy for this release build
        id: {POLICY_STEP}
        uses: $/.github/actions/evaluate-build-policy
        with:
          inputs-json: ${{{{ toJSON(inputs) }}}}
          build-type: release-candidate
      - name: Require a release-build candidate without image preflight
        env:
          RUN_CANDIDATE: ${{{{ steps.{POLICY_STEP}.outputs.run-candidate }}}}
          IMAGE_PREFLIGHT: ${{{{ steps.{POLICY_STEP}.outputs.image-preflight }}}}
          CANDIDATE_ROLE: ${{{{ inputs.candidate-role }}}}
        run: |
          if [[ "${{RUN_CANDIDATE}}" != true || "${{IMAGE_PREFLIGHT}}" != false || "${{CANDIDATE_ROLE}}" != release-build ]]; then
            echo "release build entrypoints run only release-build candidates without image preflight" >&2
            exit 1
          fi
"""
REPLACEMENTS = (
    ("needs.policy.outputs.", f"steps.{POLICY_STEP}.outputs."),
    # Only read by steps that run when image preflight input is given, which the policy step refuses.
    ("${{ needs.prepare-build-matrix.outputs.preflight-document-sha256 }}", '""'),
)


class EntrypointError(ValueError):
    """A candidate workflow no longer has the shape this generator transforms."""


def _block(lines: list[str], start: int) -> int:
    """Return the end of the two-space-indented job block starting at ``start``."""
    end = start + 1
    while end < len(lines) and not re.match(r"^  \S", lines[end]) and not re.match(r"^\S", lines[end]):
        end += 1
    return end


def _name_the_build(body: str, family: str) -> str:
    """Give every dependency setup step the build this row runs, which goes into the row's reuse key.

    A repository's C++ and Python rows share unit, family, arch, CUDA and Python; only the entrypoint and its inputs
    tell them apart.
    """
    lines = body.splitlines(keepends=True)
    result: list[str] = []
    in_setup = False
    named = 0
    for line in lines:
        if line.startswith("      - "):
            in_setup = False
        if line.startswith("        uses: rapidsai/shared-actions/release-candidate-dependencies@"):
            in_setup = True
        result.append(line)
        if in_setup and line == "        with:\n":
            result.append(f"          row-entrypoint: {family}-release\n")
            result.append("          row-inputs: ${{ toJSON(inputs) }}\n")
            named += 1
            in_setup = False
    if named == 0:
        raise EntrypointError(f"{family}-candidate.yaml has no dependency setup step to name the build in")
    return "".join(result)


def _skip_reused_rows(body: str, family: str) -> str:
    """Insert the reuse step after dependency setup and make every later step skip when the row was reused."""
    lines = body.splitlines(keepends=True)
    if lines.count(SETUP_STEP) != 1:
        raise EntrypointError(f"{family}-candidate.yaml has no single dependency setup step")
    end = lines.index(SETUP_STEP) + 1
    while end < len(lines) and not lines[end].startswith("      - "):
        end += 1
    starts = [index for index in range(end, len(lines)) if lines[index].startswith("      - ")]
    later = []
    for position, start in enumerate(starts):
        stop = starts[position + 1] if position + 1 < len(starts) else len(lines)
        later.extend(_skip_when_reused(lines[start:stop], family))
    return "".join([*lines[:end], REUSE_STEP, *later])


def _skip_when_reused(step: list[str], family: str) -> list[str]:
    """Add the reuse condition to one step's single-line condition, or give it one."""
    conditions = [index for index, line in enumerate(step) if line.startswith("        if: ")]
    if not conditions:
        return [step[0], f"        if: ${{{{ {REUSED_CONDITION} }}}}\n", *step[1:]]
    index = conditions[0]
    expression = step[index].removeprefix("        if: ").strip()
    if len(conditions) > 1 or not expression or expression in {">", ">-", "|", "|-"}:
        raise EntrypointError(f"{family}-candidate.yaml has a step condition this generator cannot extend")
    inner = expression.removeprefix("${{").removesuffix("}}").strip()
    return [*step[:index], f"        if: ${{{{ ({inner}) && {REUSED_CONDITION} }}}}\n", *step[index + 1 :]]


def generate(text: str, family: str) -> str:
    """Return the release-build entrypoint for one candidate workflow's text."""
    lines = text.splitlines(keepends=True)
    try:
        jobs = lines.index("jobs:\n")
        inputs = lines.index("    inputs:\n")
        build = lines.index("  build:\n", jobs)
    except ValueError as error:
        raise EntrypointError(f"{family}-candidate.yaml has no jobs, inputs or build job") from error
    end = _block(lines, build)
    job = lines[build:end]
    edited: list[str] = []
    seen = {"needs": 0, "if": 0, "matrix": 0, "steps": 0, "image": 0}
    in_container = False
    for line in job:
        if line == "    container:\n":
            in_container = True
        elif re.match(r"^    \S", line):
            in_container = False
        if in_container and line.startswith("      image: "):
            seen["image"] += 1
            edited.append(CONTAINER_LINES)
            continue
        if line.startswith("    needs: "):
            seen["needs"] += 1
            continue
        if line.startswith("    if: "):
            seen["if"] += 1
            continue
        if re.match(r"^      matrix: \$\{\{ fromJSON\(needs\.[a-z-]+\.outputs\.matrix\) \}\}\n$", line):
            seen["matrix"] += 1
            edited.append(f"      matrix: ${{{{ fromJSON(inputs.{MATRIX_INPUT}) }}}}\n")
            continue
        edited.append(line)
        if line == "    steps:\n":
            seen["steps"] += 1
            edited.append(IMAGE_STEP.format(expression=IMAGE_EXPRESSION, family=IMAGE_FAMILIES[family]))
            edited.append(POLICY_STEPS)
    if seen["needs"] != 1 or seen["matrix"] != 1 or seen["steps"] != 1 or seen["if"] > 1 or seen["image"] != 1:
        raise EntrypointError(f"{family}-candidate.yaml build job changed shape: {seen}")
    body = "".join(edited)
    for old, new in REPLACEMENTS:
        body = body.replace(old, new)
    body = _name_the_build(body, family)
    body = _skip_reused_rows(body, family)
    if "needs." in body:
        raise EntrypointError(f"{family}-candidate.yaml build job reads another job: {re.findall(r'needs[.][\\w.-]+', body)}")
    preamble = lines[:jobs]
    preamble.insert(inputs + 1, MATRIX_INPUT_TEXT + IMAGE_MAP_INPUT_TEXT)
    # Keep the copyright line first; the generated-file notice follows it.
    copyright_lines = 1 if preamble and preamble[0].startswith("# Copyright") else 0
    preamble.insert(copyright_lines, HEADER.format(source=f".github/workflows/{family}-candidate.yaml"))
    result = "".join(preamble) + "jobs:\n" + body
    document = yaml.safe_load(result)
    if list(document["jobs"]) != ["build"] or MATRIX_INPUT not in document[True]["workflow_call"]["inputs"]:
        raise EntrypointError(f"generated {family}-release.yaml is not a single build job with {MATRIX_INPUT}")
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if a generated entrypoint is out of date.")
    args = parser.parse_args(argv)
    stale = []
    for family in FAMILIES:
        expected = generate((WORKFLOWS / f"{family}-candidate.yaml").read_text(), family)
        target = WORKFLOWS / f"{family}-release.yaml"
        if target.exists() and target.read_text() == expected:
            continue
        if args.check:
            stale.append(target.name)
        else:
            target.write_text(expected)
    if stale:
        print(f"regenerate with ci/release_build_entrypoints.py: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
